/* Mở / đóng bài viết */
(function () {
  const modal = document.getElementById("article-modal");
  const titleEl = document.getElementById("article-title");
  const bodyEl = document.getElementById("article-body");
  if (!modal) return;

  function openArticle(i) {
    titleEl.textContent = ARTICLES[i].t;
    bodyEl.innerHTML = ARTICLES[i].h;
    modal.classList.add("open");
    document.body.style.overflow = "hidden";
  }
  function closeArticle() {
    modal.classList.remove("open");
    document.body.style.overflow = "";
  }

  document.querySelectorAll(".news-item").forEach((el, i) => {
    el.style.cursor = "pointer";
    el.addEventListener("click", () => openArticle(i));
  });
  document.getElementById("article-close").addEventListener("click", closeArticle);
  modal.addEventListener("click", (e) => { if (e.target === modal) closeArticle(); });
  document.addEventListener("keydown", (e) => { if (e.key === "Escape") closeArticle(); });
})();
